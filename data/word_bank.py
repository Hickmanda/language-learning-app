def find_course(course_id):
    for c in COURSES:
        if c["id"] == course_id:
            return c
    return None


def count_words(course):
    return sum(len(t["words"]) for t in course["topics"])


def search_words(query, learn_lang, base_lang):
    q = query.strip().lower()
    if not q:
        return []
    results = []
    for course in COURSES:
        for topic in course["topics"]:
            for w in topic["words"]:
                learn_val = str(w.get(learn_lang, "")).lower()
                base_val = str(w.get(base_lang, "")).lower()
                if q in learn_val or q in base_val:
                    results.append({"word": w, "course": course, "topic": topic})
    return results